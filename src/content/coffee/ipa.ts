// sequências com pronúncia própria
export const PAIRS: Record<string, string> = {
  'used to': 'ˈjustə',
  'have to': 'ˈhæftə',
  'going to': 'ˈɡoʊɪŋtə',
  'want to': 'ˈwɑntə',
};

const VOWEL = /^[ˈˌ]?[aeiouæɑɔəɛɪʊʌɜ]/;

const normalize = (text: string) =>
  text
    .toLowerCase()
    .replace(/[’]/g, "'")
    .replace(/[^a-z' -]/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);

// IPA de uma palavra ou expressão, entre barras. null se alguma palavra não estiver no dicionário.
export function ipaFor(text: string): string | null {
  const words = normalize(text);
  if (words.length === 0) return null;
  const out: string[] = [];
  for (let i = 0; i < words.length; i++) {
    const pair = words[i + 1] ? PAIRS[`${words[i]} ${words[i + 1]}`] : undefined;
    if (pair) {
      out.push(pair);
      i++;
      continue;
    }
    const e = WORD_IPA[words[i]];
    if (!e) return null;
    if (typeof e === 'string') {
      out.push(e);
      continue;
    }
    const alone = words.length === 1;
    if (words[i] === 'the') {
      // "the" antes de vogal: /ði/ (the apple); antes de consoante: /ðə/
      const next = words[i + 1] ? WORD_IPA[words[i + 1]] : undefined;
      const nextIpa = typeof next === 'string' ? next : next?.[0];
      out.push(alone || (nextIpa && VOWEL.test(nextIpa)) ? e[0] : e[1]);
      continue;
    }
    out.push(alone ? e[0] : e[1]);
  }
  return `/${out.join(' ')}/`;
}

